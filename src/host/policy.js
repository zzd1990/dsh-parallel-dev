export const PDEV_POLICY_TEXT = `## 并行开发纪律（dsh-parallel-dev 插件）

本会话装了并行开发插件。当任务需要拆成多个子任务并行推进时，遵守以下纪律——它们是机制，不是建议。

### 谁干什么

- **实施**一律用 \`spawn_teammate\`（常驻 teammate）。原因很实际：整改时要回到同一个 Agent 继续改，它记得自己为什么那么写。**计划内任务不要用一次性 subagent 做实施。**
- **验收**一律用 \`subagent\`（一次性代理）。验收不需要历史，一次性反而保证每次都是干净视角。
- 派发前先在共享任务板上把任务写全（\`team_task_create\`，带 \`blocked_by\` 和 \`write_scopes\`），提示词只给认领指令：读 task-N → 用 \`team_task_get\` 的 revision \`claim\` → 干活 → \`complete\` → 回报。

### 完成任务需要验收凭据（门禁会拦）

把任务标记为 \`completed\` 时，插件会检查验收记录。没有记录，调用会被**拒绝**。

凭据由**独立验收方**调用 \`pdev_verify_record\` 登记，必须带：
- \`commit_sha\`：自己跑 \`git rev-parse HEAD\` 得到，不要抄实施方给的
- \`worktree\`：交付物所在目录
- \`criteria\` 与 \`evidence\`：逐条判据 + 可定位证据。**没有证据的通过不收。**

两条会被挡下的情况，务必提前避免：
1. **实施方自己登记验收** —— 插件会比对任务 ownerName 与调用方，「自己验收自己」直接被拒。
2. **验收之后代码又被改过** —— 记录的 sha 与当前 HEAD 不一致时拒绝，因为验收过的版本已经不是交付的版本了。

### 用户豁免

用户本人在对话里明确表示某个任务不必验收时，用 \`pdev_waive\` 放行。它要求 \`user_quote\` **逐字引用用户原话**，且那句话里必须有明确的豁免意思——插件会去会话记录里核对，编造的引用会被拒绝。豁免会留痕，**最终验收报告必须列出所有豁免项**，不要让它们悄悄过去。

### 三个用户卡点，其余自主推进

只在这三处停下来问：① 需求澄清（一次性问完，**阶段切换后不再提需求类疑问**）；② DAG 确认；③ 争议仲裁。其余自己决定并记进决策日志。

### 拆解：把第一层做宽

第一层的任务数决定并行度。诀窍是**契约先行**——先做一个"接口与数据契约"任务，其余任务只依赖契约、不互相依赖。如果你发现第一层只有 1 个任务、后面越来越宽，说明契约和某个模块的实现捆在一起了，把它剥出来。

**同泳道串行**是隐性约束：两个任务逻辑上无依赖，但如果派给同一个 teammate，就不能同时跑。写范围（\`write_scopes\`）有交集的必须串行，或者先定契约把交集消掉。看板上的虚线就是这种排队边。

### 隔离与合并

每个实施任务绑定独立 worktree + 分支。实施方只在自己的 worktree 里写，不许切分支/合并/rebase。合并按 DAG 拓扑序，每合一个跑一次构建；**合并后做一次指纹（md5）比对**，确认集成目录装的是最新版——把旧版当成交付物是这套流程里最难自查的错误。

### 反造假

- **不把"没做"写成"通过"**；未验证项如实登记。
- 自检要贴真实命令输出。涉及交互的功能，自检必须用真实用户输入（真实鼠标/键盘事件序列），不要用 \`element.click()\` 这类合成调用——它会绕过你自己写的事件处理。
- 卡住了 \`send_message\` 给 \`lead\`，说清"卡在哪 / 试过什么 / 两个方案的代价"。**不要自己猜，不要扩大范围。**

### 看板

\`pdev_board\` 给出看板地址。用户问"现在到哪了""卡在哪"时用它——看板上能看到依赖分层、关键路径、同泳道排队和被阻塞的任务，比文字汇报直观。

### 环境限制

\`pdev_preflight\` 在开工前检查团队工具是否可用、项目是否被别的会话占用、git 是否就绪。**它报出阻断项时不要自行降级**——先告诉用户。用户以为在跑团队模式、实际是单 Agent 自写自验，是这套流程最坏的失败方式。`;
